import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const noticeName = 'THIRD_PARTY_NOTICES.txt';
const npmNotices = JSON.parse(readFileSync(join(root, 'third_party/npm-notices.json'), 'utf8'));
const header = `Tiller third-party notices

Tiller's own code is licensed under Apache 2.0; see LICENSE and NOTICE. The
components below retain their upstream licenses. License and copyright text
is copied from upstream distributions or versioned source, not inferred from
SPDX labels.

Generated by scripts/third-party-notices.mjs. Do not edit this file.
Reinstall dependencies and rebuild the console/site after dependency changes.

`;

function componentNotices(components, directory) {
  return components.map(component => section(
    `${component.name} ${component.version}${component.scope ? ` (${component.scope})` : ''}\nSource: ${component.source}`,
    component.files.map(file => `--- ${file} ---\n${readFileSync(join(directory, file), 'utf8').trimEnd()}\n`).join('\n'),
  )).join('');
}

// Include NOTICE alongside LICENSE, and all files in a license directory (for
// example Pagefind's separately attributed code). Never substitute a URL.
export function licenseTexts(directory) {
  const files = [];
  for (const name of readdirSync(directory).sort()) {
    if (!/^(licen[sc]e|copying|copyright|notice)([._-]|$)/i.test(name)) continue;
    const path = join(directory, name);
    if (statSync(path).isDirectory()) {
      for (const child of readdirSync(path).sort()) {
        if (statSync(join(path, child)).isFile()) files.push(join(name, child));
      }
    } else {
      files.push(name);
    }
  }
  const installedText = files.map(name => `--- ${name} ---\n${readFileSync(join(directory, name), 'utf8').trimEnd()}\n`).join('\n');
  if (!files.some(name => /^(licen[sc]e|copying)([._/-]|$)/i.test(name))) {
    const metadataPath = join(directory, 'package.json');
    if (existsSync(metadataPath)) {
      const pkg = JSON.parse(readFileSync(metadataPath, 'utf8'));
      const upstream = npmNotices[`${pkg.name}@${pkg.version}`];
      if (upstream) return componentNotices(upstream.components, join(root, 'third_party')) + installedText;
    }
    throw new Error(`No upstream license text in ${directory}; add the actual upstream text before distributing it`);
  }
  return installedText;
}

function section(label, text) {
  return `================================================================\n${label}\n================================================================\n\n${text.trimEnd()}\n\n`;
}

export function bundledPackageRoots(moduleIds) {
  const directories = new Set();
  for (const id of moduleIds) {
    const path = id.replace(/^\0/, '').split('?')[0];
    const marker = '/node_modules/';
    const start = path.lastIndexOf(marker);
    if (start < 0) continue;
    const parts = path.slice(start + marker.length).split('/');
    const name = parts[0].startsWith('@') ? parts.slice(0, 2).join('/') : parts[0];
    directories.add(path.slice(0, start + marker.length) + name);
  }
  return directories;
}

export function packageNotices(directories) {
  const entries = new Map();
  for (const directory of directories) {
    const pkg = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'));
    const label = `${pkg.name} ${pkg.version}`;
    let text = licenseTexts(directory);
    if (pkg.name === 'pagefind') {
      const sourceDirectory = join(root, 'third_party', `pagefind-wasm-${pkg.version}`);
      const manifest = JSON.parse(readFileSync(join(sourceDirectory, 'manifest.json'), 'utf8'));
      if (manifest.pagefindVersion !== pkg.version) throw new Error('Pagefind WASM source/license version mismatch');
      text += '\n' + componentNotices(manifest.components, sourceDirectory);
      text += '\n' + pagefindJavaScriptNotices(pkg.version);
    }
    if (entries.has(label) && entries.get(label) !== text) {
      throw new Error(`Conflicting upstream notices for ${label}`);
    }
    entries.set(label, text);
  }
  return [...entries].sort(([a], [b]) => a.localeCompare(b, 'en')).map(([label, text]) => section(label, text)).join('');
}

function pagefindJavaScriptNotices(version) {
  const emitted = npmNotices[`pagefind@${version}`];
  const ui = npmNotices[`@pagefind/default-ui@${version}`];
  if (!emitted || !ui) throw new Error(`Missing versioned Pagefind JavaScript closure for ${version}`);
  return componentNotices([...ui.components, ...emitted.components], join(root, 'third_party'));
}

// Pagefind emits these prebundled assets after Vite, so they never enter the
// Vite module graph. Inventory the actual final files against the exact
// version's upstream source/lock closure rather than treating them as MIT-only.
export function pagefindEmittedJavaScriptNotices(directory, version) {
  const emitted = npmNotices[`pagefind@${version}`];
  if (!emitted) throw new Error(`Missing versioned Pagefind JavaScript closure for ${version}`);
  const actual = readdirSync(directory).filter(file => file.endsWith('.js')).sort();
  const expected = [...emitted.emittedFiles].sort();
  if (actual.join('\n') !== expected.join('\n')) {
    throw new Error(`Pagefind ${version} emitted JavaScript closure changed; review upstream notices (${actual.join(', ')})`);
  }
  return pagefindJavaScriptNotices(version);
}

function fontNotices() {
  return ['Inter', 'Space-Grotesk', 'Space-Mono'].map(name => {
    const text = readFileSync(join(root, 'ui/public/fonts', `${name}-OFL.txt`), 'utf8');
    // The console's font licenses are the source; keep both website copies in
    // step when either surface regenerates its notices.
    for (const directory of ['site/src/fonts', 'site/public/fonts']) {
      writeIfChanged(join(root, directory, `${name}-OFL.txt`), text);
    }
    return section(`${name} font (SIL Open Font License 1.1)`, text);
  }).join('');
}

// Run the toolchain go.mod selects, never a newer local one. The recorded
// standard-library version is part of the committed notices, so a contributor's
// Go must not change it.
export function goToolchain(goMod) {
  const toolchain = goMod.match(/^toolchain\s+(go\S+)\s*$/m)?.[1];
  if (toolchain) return toolchain;
  const version = goMod.match(/^go\s+(\d+\.\d+(?:\.\d+)?)\s*$/m)?.[1];
  if (!version) throw new Error('go.mod names no go version');
  return `go${version.split('.').length === 2 ? `${version}.0` : version}`;
}

function goEnvironment(extra = {}) {
  return { ...process.env, ...extra, GOTOOLCHAIN: goToolchain(readFileSync(join(root, 'go.mod'), 'utf8')) };
}

function goNotices() {
  const modules = new Map();
  // Inventory the real executable, not every go.mod entry (test dependencies
  // are not shipped), and union every supported release platform.
  for (const GOOS of ['darwin', 'linux']) {
    for (const GOARCH of ['amd64', 'arm64']) {
      const output = execFileSync('go', ['list', '-deps', '-f',
        '{{if .Module}}{{if not .Module.Main}}{{.Module.Path}}\t{{.Module.Version}}\t{{.Module.Dir}}{{end}}{{end}}',
        './cmd/tiller'], { cwd: root, encoding: 'utf8', env: goEnvironment({ GOOS, GOARCH, CGO_ENABLED: '0' }) });
      for (const line of output.split('\n').filter(Boolean)) {
        const [name, version, directory] = line.split('\t');
        modules.set(`${name} ${version}`, directory);
      }
    }
  }
  const goroot = execFileSync('go', ['env', 'GOROOT'], { cwd: root, encoding: 'utf8', env: goEnvironment() }).trim();
  const version = execFileSync('go', ['env', 'GOVERSION'], { cwd: root, encoding: 'utf8', env: goEnvironment() }).trim();
  return section(`Go standard library ${version}`, readFileSync(join(goroot, 'LICENSE'), 'utf8')) +
    [...modules].sort(([a], [b]) => a.localeCompare(b, 'en')).map(([label, directory]) => section(label, licenseTexts(directory))).join('');
}

function writeIfChanged(path, content) {
  if (!existsSync(path) || readFileSync(path, 'utf8') !== content) writeFileSync(path, content);
}

function writeConsole(javascript) {
  const text = header + 'Go runtime dependencies\n\n' + goNotices() +
    'Console JavaScript dependencies\n\n' + javascript + 'Fonts\n\n' + fontNotices();
  writeIfChanged(join(root, noticeName), text);
  writeIfChanged(join(root, 'ui/public', noticeName), text);
  return text;
}

function siteSeeds() {
  // Starlight and Expressive Code inline code/CSS; Pagefind emits its search
  // assets after Vite finishes. They therefore cannot be found only by looking
  // at Vite's final JavaScript chunks.
  return new Set(['astro', '@astrojs/starlight', '@expressive-code/core',
    '@expressive-code/plugin-frames', '@expressive-code/plugin-shiki',
    'expressive-code', 'astro-expressive-code', 'pagefind', '@pagefind/default-ui', 'vite'].map(name => join(root, 'site/node_modules', name)));
}

export function pagefindSourceArchive() {
  const pkg = JSON.parse(readFileSync(join(root, 'site/node_modules/pagefind/package.json'), 'utf8'));
  return `pagefind-${pkg.version}-corresponding-source.tar.gz`;
}

function websiteNotices(directories) {
  const archive = pagefindSourceArchive();
  if (!existsSync(join(root, 'site/public', archive))) throw new Error(`Missing Pagefind corresponding source: ${archive}`);
  return header + 'Pagefind WebAssembly search incorporates GPL-licensed code. Its full corresponding\n' +
    `source, linked dependency sources, upstream build scripts, and licenses are available\nat /tiller/${archive}\n\n` +
    'Website dependencies (bundled and inline code, CSS, and search assets)\n\n' +
    packageNotices(directories) + 'Fonts\n\n' + fontNotices();
}

// Vite/Rolldown provide the actual bundled module closure, including transitive
// production dependencies. Do not infer it from the five top-level imports.
export function noticesPlugin(surface) {
  // Vite's generated module-preload helper is runtime code but has a virtual
  // module ID, so include its upstream notices explicitly.
  const directories = surface === 'site' ? siteSeeds() : new Set([join(root, 'ui/node_modules/vite')]);
  return {
    name: 'tiller-third-party-notices',
    apply: 'build',
    generateBundle(_options, bundle) {
      for (const output of Object.values(bundle)) {
        if (output.type !== 'chunk') continue;
        for (const directory of bundledPackageRoots(Object.keys(output.modules))) directories.add(directory);
      }
      if (surface === 'ui') {
        const text = writeConsole(packageNotices(directories));
        this.emitFile({ type: 'asset', fileName: noticeName, source: text });
      } else {
        writeIfChanged(join(root, 'site/public', noticeName), websiteNotices(directories));
      }
    },
  };
}

// Astro copies public/ before its client build. Write the final union after the
// client bundle and Pagefind have finished, rather than distributing stale text.
export function noticesIntegration() {
  return {
    name: 'tiller-third-party-notices',
    hooks: {
      'astro:build:done': ({ dir }) => {
        const outputDirectory = fileURLToPath(dir);
        const pkg = JSON.parse(readFileSync(join(root, 'site/node_modules/pagefind/package.json'), 'utf8'));
        const emitted = pagefindEmittedJavaScriptNotices(join(outputDirectory, 'pagefind'), pkg.version);
        const text = readFileSync(join(root, 'site/public', noticeName), 'utf8');
        if (!text.includes(emitted)) throw new Error('Missing full emitted Pagefind JavaScript notices');
        writeIfChanged(join(outputDirectory, noticeName), text);
      },
    },
  };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  // Before the first build, include the entire installed production dependency
  // closure as a conservative source inventory. A console build replaces this
  // with its precise bundled closure and emits the same text into dist.
  const lock = JSON.parse(readFileSync(join(root, 'ui/package-lock.json'), 'utf8'));
  const directories = Object.entries(lock.packages).filter(([path, pkg]) => path && !pkg.dev)
    .map(([path, pkg]) => {
      const directory = join(root, 'ui', path);
      const installed = JSON.parse(readFileSync(join(directory, 'package.json'), 'utf8'));
      if (installed.version !== pkg.version) throw new Error(`Run npm ci in ui: ${path} differs from package-lock.json`);
      return directory;
    });
  directories.push(join(root, 'ui/node_modules/vite'));
  writeConsole(packageNotices(directories));
  writeIfChanged(join(root, 'site/public', noticeName), websiteNotices(siteSeeds()));
}
